/**
 * ジャンル/タグの色をそのまま文字色（や、白文字を乗せる背景）に使うと、
 * 薄すぎる色を選んだ時にほぼ読めなくなる。黒へ45%までしか寄せないことで、
 * 自由入力の白に近い色を選んだ最悪ケースでもコントラスト比 4.5:1 を確保する。
 */
export function readableColor(color: string) {
  return `color-mix(in srgb, ${color} 45%, #000)`
}
